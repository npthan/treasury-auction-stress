def test_no_currently_tracked_text_file_contains_an_absolute_home_path():
    """Regression guard for the Phase 9 finding that an early committed
    working-log report embedded a real local
    /Users/<username>/... path. Scans every git-tracked file in the
    current working tree, not just that one file, so the same defect
    class is caught anywhere it recurs, not just at its original site.

    Applies the same reviewed fingerprint allowlist audit_cli.py uses
    (configs/governance_audit_allowlist.yml): a handful of tracked files
    legitimately match this pattern on purpose -- documentation prose
    describing the pattern abstractly, and this project's own
    deliberately-fake canary test fixtures -- each individually
    reviewed there, never exempted by path or category.
    """
    tracked = subprocess.run(
        ["git", "ls-files"],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
        check=True,
    ).stdout.splitlines()

    allowed = _load_allowlist_fingerprints(REPO_ROOT)
    offenders: list[str] = []
    for rel_path in tracked:
        full_path = REPO_ROOT / rel_path
        if not full_path.is_file():
            continue
        try:
            text = full_path.read_text(encoding="utf-8")
        except (UnicodeDecodeError, OSError):
            continue  # binary or unreadable; not a text-leak candidate
        findings = [
            f
            for f in scan_for_identifying_info(text, location=rel_path)
            if f.category == "identifying_info:absolute_home_path"
            and allowlist_token(rel_path, f.fingerprint) not in allowed
        ]
        if findings:
            offenders.append(rel_path)

    assert offenders == [], f"absolute local path found in: {offenders}"


