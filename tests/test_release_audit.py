# --- Second acceptance-review remediation (public-history/identity/
# license decisions): current-tree audit must pass end-to-end now that
# the private email is removed, and must fail again if either the email
# or a local home path is reintroduced. ---


def _current_tracked_paths_and_contents() -> list[tuple[str, str]]:
    """Every path that would be tracked after `git add -A` -- i.e. the
    real current working-tree state, not the stale index. `git ls-files`
    alone still lists a path deleted-on-disk-but-not-yet-staged (exactly
    the case for the two removed real RTDSM fixtures right now), which
    would make this a false negative for "is anything unsafe currently
    on disk." `git ls-files --others --exclude-standard` adds new,
    not-yet-staged, not-gitignored files.
    """
    tracked = subprocess.run(
        ["git", "ls-files"], cwd=REPO_ROOT, capture_output=True, text=True, check=True
    ).stdout.splitlines()
    untracked = subprocess.run(
        ["git", "ls-files", "--others", "--exclude-standard"],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
        check=True,
    ).stdout.splitlines()
    all_paths = sorted(set(tracked) | set(untracked))
    out = []
    for rel_path in all_paths:
        full_path = REPO_ROOT / rel_path
        if not full_path.is_file():
            continue  # deleted-but-still-indexed; not actually on disk
        try:
            text = full_path.read_text(encoding="utf-8")
        except (UnicodeDecodeError, OSError):
            text = ""
        out.append((rel_path, text))
    return out


def test_current_repository_tree_passes_the_full_audit():
    """End-to-end regression guard: the actual current proposed public
    tree (not a synthetic fileset), scanned with the same reviewed
    allowlist audit_cli.py applies (configs/governance_audit_allowlist.yml
    -- every entry there is this project's own deliberately-fake test
    canary or benign doc prose, individually reviewed; see that file),
    must pass audit_tree() with `passed is True`. Note `result.findings`
    still LISTS every hard_block-severity match regardless of the
    allowlist (only `passed` reflects the allowlist decision) -- see
    tests/test_governance_audit_allowlist.py for a check that every
    *unallowlisted* hard_block finding is specifically accounted for.
    If this ever regresses to `passed is False`, either something
    sensitive was reintroduced into a tracked file, or a new test canary
    needs a new reviewed allowlist entry.
    """
    allowed = _load_allowlist_fingerprints(REPO_ROOT)
    result = audit_tree(_current_tracked_paths_and_contents(), allowed_identifying_info=allowed)
    assert result.passed is True


