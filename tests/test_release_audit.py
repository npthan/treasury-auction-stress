def test_session_url_detected_regardless_of_domain_or_tld():
    """The session-URL detector is domain-agnostic: it keys on the
    '<host>/code/session_<id>' shape, not on any specific vendor domain
    or top-level domain, so an arbitrary or newly-registered domain
    cannot bypass it. Sample values are assembled from parts so this
    test file itself contains only the one reviewed literal canary
    (FAKE_SESSION_URL_LINE)."""
    hosts = [
        "example.invalid",
        "tool.example.com",
        "internal-host.example.org",
        "sub.host.example.net",
        "short.io",
    ]
    for host in hosts:
        text = "trace at https://" + host + "/code/" + "session_" + "abc012DEF\n"
        findings = scan_for_identifying_info(text, location="notes.md")
        flagged = [
            f for f in findings if f.category == "identifying_info:dev_session_url"
        ]
        assert flagged, f"session URL on host {host!r} was not detected"
        assert all(f.severity == "hard_block" for f in flagged)

    # A bare hostless mention must NOT trip the detector -- ordinary
    # prose about sessions stays legal.
    benign = scan_for_identifying_info(
        "the session_id column is documented here\n", location="notes.md"
    )
    assert not any(
        f.category == "identifying_info:dev_session_url" for f in benign
    )


def test_allowlisted_session_canary_is_path_and_fingerprint_specific():
    """An allowlist entry permits one exact value at one exact path
    only. The reviewed canary passes at its approved path; the SAME
    canary value at any other path still hard-blocks, and a DIFFERENT
    session value at the approved path still hard-blocks."""
    fp = next(
        f.fingerprint
        for f in scan_for_identifying_info(FAKE_SESSION_URL_LINE)
        if f.category == "identifying_info:dev_session_url"
    )
    approved_entry = allowlist_token("tests/test_release_audit.py", fp)

    at_approved_path = audit_tree(
        [("tests/test_release_audit.py", FAKE_SESSION_URL_LINE)],
        allowed_identifying_info=frozenset({approved_entry}),
    )
    assert at_approved_path.passed is True

    same_canary_other_path = audit_tree(
        [("docs/notes.md", FAKE_SESSION_URL_LINE)],
        allowed_identifying_info=frozenset({approved_entry}),
    )
    assert same_canary_other_path.passed is False

    different_value_approved_path = audit_tree(
        [
            (
                "tests/test_release_audit.py",
                "see https://example.invalid/code/" + "session_" + "fedcba987654\n",
            )
        ],
        allowed_identifying_info=frozenset({approved_entry}),
    )
    assert different_value_approved_path.passed is False


