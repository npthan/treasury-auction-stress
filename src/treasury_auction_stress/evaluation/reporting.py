def _fmt(value) -> str:
    if value is None or (isinstance(value, float) and pd.isna(value)):
        return "n/a"
    if isinstance(value, bool):
        return str(value)
    if isinstance(value, float):
        return f"{value:.3f}"
    return str(value)


def df_to_markdown(df: pd.DataFrame) -> str:
    """A dependency-free Markdown table renderer (no `tabulate`
    installed; adding it for report formatting alone is not a clear
    enough need per `docs/project_rules.md`)."""
    if df.empty:
        return "_(no rows)_"
    header = "| " + " | ".join(str(c) for c in df.columns) + " |"
    sep = "|" + "|".join(["---"] * len(df.columns)) + "|"
    lines = [header, sep]
    for _, row in df.iterrows():
        lines.append("| " + " | ".join(_fmt(v) for v in row) + " |")
    return "\n".join(lines)


def build_paired_cutoff_comparison(predictions: pd.DataFrame, *, target_name: str, model_ids: list[str]) -> pd.DataFrame:
    """For each model: paired difference in absolute error
    (pre_auction - announcement) on EXACTLY matched auctions, complete
    years only. A negative mean paired difference means the pre-auction
    cutoff view had lower error on average -- an observational,
    later-information comparison, never described as causal."""
    scale = 100.0 if target_name in {"primary_dealer_share", "direct_bidder_share", "indirect_bidder_share"} else 1.0
    rows = []
    subset = predictions.loc[(predictions["target_name"] == target_name) & (~predictions["is_provisional"])]
    for model_id in model_ids:
        model_subset = subset.loc[subset["model_id"] == model_id]
        ann = model_subset.loc[model_subset["cutoff_view"] == "announcement", ["auction_key", "actual", "forecast"]]
        pre = model_subset.loc[model_subset["cutoff_view"] == "pre_auction", ["auction_key", "actual", "forecast"]]
        merged = ann.merge(pre, on="auction_key", suffixes=("_ann", "_pre"), how="inner")
        if len(merged) != len(ann) or len(merged) != len(pre):
            raise AssertionError(f"build_paired_cutoff_comparison: {model_id} cutoff views do not share an identical key set")
        ae_ann = (merged["forecast_ann"] - merged["actual_ann"]).abs() * scale
        ae_pre = (merged["forecast_pre"] - merged["actual_pre"]).abs() * scale
        rows.append(
            {
                "model_id": model_id,
                "n_matched": len(merged),
                "mae_announcement": float(ae_ann.mean()),
                "mae_pre_auction": float(ae_pre.mean()),
                "mean_paired_diff_pre_minus_ann": float((ae_pre - ae_ann).mean()),
                "n_pre_auction_better": int((ae_pre < ae_ann).sum()),
                "n_announcement_better": int((ae_ann < ae_pre).sum()),
                "n_tied": int((ae_ann == ae_pre).sum()),
            }
        )
    return pd.DataFrame(rows)


